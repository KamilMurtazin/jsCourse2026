// Сложение и короткая запись присваивания.
let count = 10;
count = count + 1;
console.log(count); // 11
count += 1;
console.log(count); // 12

// Вычитание.
count = count - 1;
console.log(count); // 11
count -= 1;
console.log(count); // 10

console.log(7 * 2); // 14
console.log(7 / 2); // 3.5
console.log(3 ** 2); // 9
console.log(9 % 2); // 1 — остаток от деления
console.log(-9 % 2); // -1
console.log((2 + 3) * 4); // 20
